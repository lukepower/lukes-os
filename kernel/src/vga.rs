// Framebuffer info stored after init
struct FbInfo {
    buffer: *mut u8,
    pitch: usize,          // bytes per row of pixels
    width: usize,          // pixels
    height: usize,         // pixels
    bytes_per_pixel: usize,
    // Text grid dimensions (computed from pixel dimensions)
    cols: usize,
    rows: usize,
}

// Safety: FbInfo is only accessed behind a spinlock Mutex.
// The raw pointer points to the framebuffer mapped by the bootloader.
unsafe impl Send for FbInfo {}

static FB_INFO: Mutex<Option<FbInfo>> = Mutex::new(None);

// Cursor position (character grid coords)
static COL: core::sync::atomic::AtomicUsize = core::sync::atomic::AtomicUsize::new(0);
static ROW: core::sync::atomic::AtomicUsize = core::sync::atomic::AtomicUsize::new(0);

// Colors (RGB)
const FG_R: u8 = 0x00;
const FG_G: u8 = 0xFF;
const FG_B: u8 = 0x00;
const BG_R: u8 = 0x00;
const BG_G: u8 = 0x00;
const BG_B: u8 = 0x00;

/// Initialize the framebuffer console from bootloader BootInfo.
pub fn init(framebuffer: &'static mut bootloader_api::info::FrameBuffer) {
    let info = framebuffer.info();
    let buf = framebuffer.buffer_mut();

    let cols = info.width / font::GLYPH_WIDTH;
    let rows = info.height / font::GLYPH_HEIGHT;

    // Clear screen to black
    for byte in buf.iter_mut() {
        *byte = 0;
    }

    let fb_info = FbInfo {
        buffer: buf.as_mut_ptr(),
        pitch: info.stride * info.bytes_per_pixel,
        width: info.width,
        height: info.height,
        bytes_per_pixel: info.bytes_per_pixel,
        cols,
        rows,
    };

    *FB_INFO.lock() = Some(fb_info);

    COL.store(0, core::sync::atomic::Ordering::Relaxed);
    ROW.store(0, core::sync::atomic::Ordering::Relaxed);
}

fn put_pixel(fb: &FbInfo, x: usize, y: usize, r: u8, g: u8, b: u8) {
    if x >= fb.width || y >= fb.height {
        return;
    }
    let offset = y * fb.pitch + x * fb.bytes_per_pixel;
    unsafe {
        let ptr = fb.buffer.add(offset);
        // Framebuffer is typically BGR or RGB; bootloader uses BGR by default
        core::ptr::write_volatile(ptr, b);
        core::ptr::write_volatile(ptr.add(1), g);
        core::ptr::write_volatile(ptr.add(2), r);
    }
}

fn draw_char(fb: &FbInfo, ch: char, col: usize, row: usize) {
    let glyph = font::glyph(ch);
    let x0 = col * font::GLYPH_WIDTH;
    let y0 = row * font::GLYPH_HEIGHT;

    for (dy, &glyph_row) in glyph.iter().enumerate() {
        for dx in 0..font::GLYPH_WIDTH {
            let lit = (glyph_row >> (7 - dx)) & 1 != 0;
            let (r, g, b) = if lit {
                (FG_R, FG_G, FG_B)
            } else {
                (BG_R, BG_G, BG_B)
            };
            put_pixel(fb, x0 + dx, y0 + dy, r, g, b);
        }
    }
}

fn scroll_up(fb: &FbInfo) {
    let row_bytes = font::GLYPH_HEIGHT * fb.pitch;
    let total_text_bytes = fb.rows * row_bytes;

    unsafe {
        // Move all rows up by one text row
        core::ptr::copy(
            fb.buffer.add(row_bytes),
            fb.buffer,
            total_text_bytes.saturating_sub(row_bytes),
        );
        // Clear the last row
        let last_row_start = (fb.rows - 1) * row_bytes;
        core::ptr::write_bytes(fb.buffer.add(last_row_start), 0, row_bytes);
    }
}

pub struct Writer;

impl Writer {
    pub fn write_char(&mut self, ch: char) {
        let mut guard = FB_INFO.lock();
        let fb = match guard.as_mut() {
            Some(fb) => fb,
            None => return, // not initialized yet
        };

        let mut col = COL.load(core::sync::atomic::Ordering::Relaxed);
        let mut row = ROW.load(core::sync::atomic::Ordering::Relaxed);

        match ch {
            '\n' => {
                col = 0;
                row += 1;
            }
            ch => {
                if col >= fb.cols {
                    col = 0;
                    row += 1;
                }
                if row >= fb.rows {
                    scroll_up(fb);
                    row = fb.rows - 1;
                }
                draw_char(fb, ch, col, row);
                col += 1;
            }
        }

        if row >= fb.rows {
            scroll_up(fb);
            row = fb.rows - 1;
        }

        COL.store(col, core::sync::atomic::Ordering::Relaxed);
        ROW.store(row, core::sync::atomic::Ordering::Relaxed);
    }
}

impl fmt::Write for Writer {
    fn write_str(&mut self, s: &str) -> fmt::Result {
        for ch in s.chars() {
            self.write_char(ch);
        }
        Ok(())
    }
}

#[macro_export]
macro_rules! print {
    ($($arg:tt)*) => ($crate::vga::_print(format_args!($($arg)*)));
}

#[macro_export]
macro_rules! println {
    () => ($crate::print!("\n"));
    ($($arg:tt)*) => ($crate::print!("{}\n", format_args!($($arg)*)));
}

#[doc(hidden)]
pub fn _print(args: fmt::Arguments) {
    use core::fmt::Write;
    use x86_64::instructions::interrupts;

    interrupts::without_interrupts(|| {
        Writer.write_fmt(args).unwrap();
    });
}
